def merge_into(ui_strings: dict[str, dict[str, str]]) -> list[str]:
    """Add these strings to ``ui_strings`` in place; return the problems found.

    Never raises: a language with the wrong number of strings, a key already
    present with another value, or a language the target lacks is reported.
    """
    problems: list[str] = []
    for keys, table in ((_KEYS, _T), (_EL_KEYS, _EL_T), (_VB_KEYS, _VB_T),
                        (_GEN_KEYS, _GEN_T), (_VP_KEYS, _VP_T),
                        (_SK_KEYS, _SK_T), (_BM_KEYS, _BM_T),
                        (_VC_KEYS, _VC_T), (_ELS_KEYS, _ELS_T),
                        (_ELP_KEYS, _ELP_T), (_ELR_KEYS, _ELR_T), (_OL_KEYS, _OL_T),
                        (_OLP_KEYS, _OLP_T), (_OLF_KEYS, _OLF_T)):
        for lang in _T:
            values = table.get(lang, ())
            if len(values) != len(keys):
                problems.append(f"{lang}: {len(values)} strings for {len(keys)} keys")
    for lang, entries in MODELS_UI_STRINGS.items():
        bucket = ui_strings.get(lang)
        if bucket is None:
            problems.append(f"unknown language {lang!r}")
            continue
        for key, value in entries.items():
            existing = bucket.get(key)
            if existing is not None and existing != value:
                problems.append(f"collision {lang}.{key}")
                continue
            bucket[key] = value
    return problems
